ALTER TABLE spots
    ADD COLUMN IF NOT EXISTS latitude DECIMAL(10, 8) NULL,
    ADD COLUMN IF NOT EXISTS longitude DECIMAL(11, 8) NULL,
    ADD COLUMN IF NOT EXISTS category VARCHAR(50) NULL,
    ADD COLUMN IF NOT EXISTS image_path VARCHAR(255) NULL,
    ADD COLUMN IF NOT EXISTS user_id BIGINT NULL REFERENCES users(id);

CREATE TABLE IF NOT EXISTS spot_images (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    spot_id BIGINT NOT NULL REFERENCES spots(id) ON DELETE CASCADE,
    image_path VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
